<?php

class Heroi {
    private string $nome;

    public function __construct(string $nome){
       $this->nome = $nome;
    }

    /**
     * Get the value of nome
     */
    public function getNome(): string
    {
        return $this->nome;
    }

    /**
     * Set the value of nome
     */
    public function setNome(string $nome): self
    {
        $this->nome = $nome;

        return $this;
    }
}



?>